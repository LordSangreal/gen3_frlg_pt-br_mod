#!/usr/bin/env python3
"""Pair PokéMMO BPE XML by numeric ID; emit deterministic LuaJIT-safe chunks."""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def read(path):
    rows = {}
    for row in ET.parse(path).getroot().findall('string'):
        key = int(row.attrib['id'])
        if key in rows:
            raise ValueError(f'Duplicate XML ID: {key}')
        rows[key] = row.text or ''
    return rows


def build(english, portuguese, root):
    en, pt = read(english), read(portuguese)
    corrections = json.loads((root / 'tools/hoenn_corrections.json').read_text())
    rows, rejected, input_issues = [], [], []
    for key, source in sorted(en.items()):
        target = pt.get(key)
        if target is None:
            input_issues.append({'id': key, 'reason': 'missing_portuguese'})
        elif collections.Counter(re.findall(r'\{\d+\}', source)) != collections.Counter(re.findall(r'\{\d+\}', target)):
            input_issues.append({'id': key, 'reason': 'placeholder_mismatch'})
        target = corrections.get(str(key), target)
        reason = None
        if target is None:
            reason = 'missing_portuguese'
        elif not target.strip():
            reason = 'empty_portuguese'
        elif collections.Counter(re.findall(r'\{\d+\}', source)) != collections.Counter(re.findall(r'\{\d+\}', target)):
            reason = 'placeholder_mismatch'
        elif re.search(r'\{(?!0[1-6]\})[^}]*\}', source + target):
            reason = 'unsupported_placeholder'
        if reason:
            rejected.append({'id': key, 'reason': reason})
        else:
            # PokéMMO BPE IDs use 0x10000000 + file offset; GBA pointers use 0x08000000.
            if not 0x10000000 <= key < 0x12000000:
                raise ValueError(f'Not a BPE ROM offset: {key}')
            rows.append([f'g3:{key - 0x08000000:08x}', source, target])
    dest = root / 'lang/hoenn'
    dest.mkdir(parents=True, exist_ok=True)
    for old in dest.glob('catalog_*.lua'):
        old.unlink()
    for start in range(0, len(rows), 300):
        lines = ['-- Generated by tools/build_hoenn.py; do not edit.', 'return {']
        for row in rows[start:start + 300]:
            lines.append('  {' + ', '.join(json.dumps(s, ensure_ascii=False) for s in row) + '},')
        lines.append('}')
        (dest / f'catalog_{start // 300 + 1}.lua').write_text('\n'.join(lines) + '\n')
    report = {
        'english_entries': len(en), 'portuguese_entries': len(pt),
        'paired_ids': len(en.keys() & pt.keys()), 'eligible_entries': len(rows),
        'reviewed_corrections': len(corrections),
        'input_issues_counts': dict(collections.Counter(r['reason'] for r in input_issues)),
        'input_issues': input_issues,
        'portuguese_only_ids': sorted(pt.keys() - en.keys()),
        'excluded_counts': dict(collections.Counter(r['reason'] for r in rejected)),
        'excluded': rejected,
        'inputs': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in [english, portuguese]},
        'policy': 'Address plus English verification in Emerald; unambiguous English matching in all three games. Unmatched text remains English.',
    }
    (root / 'docs/hoenn-coverage.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k: v for k, v in report.items() if k not in ('excluded', 'inputs', 'input_issues')}, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('english', type=Path)
    parser.add_argument('portuguese', type=Path)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    build(args.english, args.portuguese, args.root)
